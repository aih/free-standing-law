#!/usr/bin/env python3
"""Check a title's reviewed table of outdated provisions and render it as Markdown.

Inputs, for title N:
  analysis/outdated/candidates/tN.json   written by tools/outdated/scan.py
  analysis/outdated/tables/tN.tsv       the reviewed table (tools/outdated/README.md)

Checks:
  - every unit a row names is an identifier in the title's USLM at the release point;
  - every candidate signal is accounted for: its section or unit is named by a row (a finding,
    or a "checked" row that records why the signal is not a finding).

Writes analysis/outdated/tables/tN.md and exits 1 if a check fails (the report lists the failures).

Usage:
    python3 tools/outdated/report.py 24 [--xml-dir data/uscode/xml]
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]  # the repository
HERE = ROOT / "analysis/outdated"
TOOL = Path(__file__).resolve().parent
CATEGORIES = {
    "outdated": "Outdated",
    "not-applicable": "Not applicable",
    "wrong": "Wrong",
    "checked": "Checked and not a finding",
}


def code_cite(ident: str) -> str:
    """'/us/usc/t11/s101/21B/C' -> '11 U.S.C. 101(21B)(C)'."""
    parts = ident.strip("/").split("/")
    if len(parts) < 4 or parts[1] != "usc":
        return ident
    title, sec = parts[2][1:], parts[3][1:]
    return f"{title} U.S.C. {sec}" + "".join(f"({p})" for p in parts[4:])


def identifiers(xml: Path) -> set[str]:
    out = set()
    for _, el in ET.iterparse(xml, events=("end",)):
        ident = el.get("identifier")
        if ident:
            out.update(ident.split())
        el.clear()
    return out


def covers(row_units: list[str], unit: str, section: str) -> bool:
    for u in row_units:
        if unit == u or unit.startswith(u + "/") or section == u:
            return True
        if unit == section and u.startswith(section + "/"):  # a note on the section
            return True
    return False


def md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("title")
    ap.add_argument("--xml-dir", default=str(ROOT / "data/uscode/xml"))
    a = ap.parse_args(argv)
    t = a.title
    cand = json.loads((HERE / f"candidates/t{t}.json").read_text())
    rows = list(csv.DictReader((HERE / f"tables/t{t}.tsv").open(encoding="utf-8"),
                               delimiter="\t"))
    xml = Path(a.xml_dir) / f"usc{t.zfill(2) if t.isdigit() else t}.xml"
    known = identifiers(xml)
    problems = []
    for r in rows:
        r["_units"] = r["units"].split()
        if r["category"] not in CATEGORIES:
            problems.append(f"{r['id']}: unknown category {r['category']!r}")
        for u in r["_units"] + [r["section"]]:
            if u not in known:
                problems.append(f"{r['id']}: {u} is not an identifier in {xml.name}")
    uncovered = []
    for s in cand["signals"]:
        if not any(covers(r["_units"] + [r["section"]], s["unit"], s["section"]) for r in rows):
            uncovered.append(s)
    for s in uncovered:
        problems.append(f"signal not accounted for: {s['kind']} {s['unit']}: {s['detail'][:120]}")

    has_draft = "draft" in rows[0]
    counts = collections.Counter(r["category"] for r in rows)
    out = [f"# Title {t}: outdated, inapplicable and wrong provisions", "",
           f"Generated by `python3 tools/outdated/report.py {t}` from `analysis/outdated/tables/t{t}.tsv` "
           f"(reviewed) and `analysis/outdated/candidates/t{t}.json` (`tools/outdated/scan.py`, "
           f"{cand['source'].split('/')[-1]}). Method: `tools/outdated/README.md`.", "",
           f"{cand['sections_in_force']} sections in force; {len(cand['signals'])} signals in "
           f"{cand['sections_with_signals']} sections; "
           + ", ".join(f"{counts[c]} {CATEGORIES[c].lower()}" for c in CATEGORIES if counts[c])
           + ".", ""]
    for cat, label in CATEGORIES.items():
        sel = [r for r in rows if r["category"] == cat]
        if not sel:
            continue
        out += [f"## {label}", ""]
        if cat == "checked":
            out += ["| Id | Provision | Signal | Why it is not a finding |", "|---|---|---|---|"]
            for r in sel:
                prov = ", ".join(code_cite(u) for u in r["_units"])
                out.append(f"| {r['id']} | {md(prov)} | {md(r['finding'])} | {md(r['evidence'] or r['recommendation'])} |")
        else:
            head = "| Id | Provision | Confidence | Finding | Evidence |"
            sep = "|---|---|---|---|---|"
            if has_draft:
                head += " Draft section | Draft treatment |"
                sep += "---|---|"
            head += " Recommendation |"
            sep += "---|"
            out += [head, sep]
            for r in sel:
                prov = ", ".join(code_cite(u) for u in r["_units"])
                line = f"| {r['id']} | {md(prov)} | {r['confidence']} | {md(r['finding'])} | {md(r['evidence'])} |"
                if has_draft:
                    line += f" {md(r['draft'])} | {md(r['draft_treatment'])} |"
                line += f" {md(r['recommendation'])} |"
                out.append(line)
        out.append("")
    out += ["## Checks", ""]
    if problems:
        out += [f"- {md(p)}" for p in problems]
    else:
        out.append(f"Every unit a row names is in {xml.name}, and every one of the "
                   f"{len(cand['signals'])} signals is accounted for by a row.")
    out.append("")
    dest = HERE / f"tables/t{t}.md"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"title {t}: {len(rows)} rows, {len(problems)} problems -> {dest}")
    for p in problems:
        print("  " + p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
